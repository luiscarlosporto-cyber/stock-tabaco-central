-- 4. Tamanho do volume de cada artigo (há volumes de 8 e de 20).
update public.products p set volume_size = v.qty
from (select product_id, max(qty) as qty from public.product_barcodes where qty > 1 group by product_id) v
where v.product_id = p.id and p.volume_size is distinct from v.qty;

-- 5. Preencher os campos principais só quando estão vazios (os restantes códigos ficam na tabela).
update public.products p set volume_barcode = b.barcode
from (select distinct on (product_id) product_id, barcode from public.product_barcodes
      where qty > 1 order by product_id, (length(barcode) = 13) desc, barcode desc) b
where b.product_id = p.id and coalesce(p.volume_barcode, '') = ''
  and not exists (select 1 from public.products x where x.volume_barcode = b.barcode or x.barcode = b.barcode);
update public.products p set barcode = b.barcode
from (select distinct on (product_id) product_id, barcode from public.product_barcodes
      where qty = 1 order by product_id, (length(barcode) = 13) desc, barcode desc) b
where b.product_id = p.id and coalesce(p.barcode, '') = ''
  and not exists (select 1 from public.products x where x.volume_barcode = b.barcode or x.barcode = b.barcode);

-- 6. Conflitos: códigos associados à mão a um artigo diferente do que o catálogo Repsol indica.
--    Deve vir vazio. Se aparecer alguma linha, corrija o código do artigo na Gestão da app.
select p.name as artigo_na_app, c.name as artigo_no_catalogo, b.barcode
from public.product_barcodes b
join public.products p on (p.barcode = b.barcode or p.volume_barcode = b.barcode) and p.id <> b.product_id
join public.products c on c.id = b.product_id;

