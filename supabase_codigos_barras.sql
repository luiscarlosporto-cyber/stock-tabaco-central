-- Códigos de barras dos artigos de tabaco, a partir do export do catálogo Repsol (26/10/2026).
-- Cada artigo pode ter vários códigos (embalagens antigas e novas). qty = maços/unidades que o código representa:
-- 1 para o maço ou unidade, 10 (ou 8, ou 20) para o volume.
-- Pode correr mais do que uma vez. Não apaga nada e só preenche os campos de código que estiverem vazios.

-- 1. Tamanho do volume por artigo (por defeito 10).
alter table public.products add column if not exists volume_size integer not null default 10;
do $$ begin
  alter table public.products add constraint products_volume_size_check check (volume_size > 0);
exception when duplicate_object then null; end $$;

-- 2. Tabela de códigos de barras.
create table if not exists public.product_barcodes (
  barcode text primary key,
  product_id text not null references public.products(id) on update cascade on delete cascade,
  qty integer not null default 1 check (qty > 0),
  created_at timestamptz not null default now()
);
create index if not exists product_barcodes_product_idx on public.product_barcodes(product_id);
alter table public.product_barcodes enable row level security;
revoke all on public.product_barcodes from anon;
grant select, insert, update, delete on public.product_barcodes to authenticated;
drop policy if exists "auth read barcodes" on public.product_barcodes;
drop policy if exists "admin write barcodes" on public.product_barcodes;
create policy "auth read barcodes" on public.product_barcodes for select to authenticated using (true);
create policy "admin write barcodes" on public.product_barcodes for all to authenticated using (public.is_admin()) with check (public.is_admin());

